export function useLang() {
  const [lang, setLangState] = React.useState(
    () => localStorage.getItem('lamar_lang') || 'ar'
  );
  const setLang = (l) => { setLangState(l); localStorage.setItem('lamar_lang', l); };
  return { lang, setLang, t: I18N[lang] || I18N.ar };
}

